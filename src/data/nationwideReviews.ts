// 7일(일주일) 간격으로 현재 날짜 기준 과거로 계산하여 실시간 연동 날짜 생성 함수
export function getFormattedDateForWeeksAgo(weeksAgo: number): string {
  const now = new Date();
  // Base date set to current date
  const targetDate = new Date(now.getTime() - weeksAgo * 7 * 24 * 60 * 60 * 1000);
  
  const year = targetDate.getFullYear();
  const month = String(targetDate.getMonth() + 1).padStart(2, '0');
  const day = String(targetDate.getDate()).padStart(2, '0');
  
  return `${year}. ${month}. ${day}`;
}

// 전체 전국 리뷰 리스트 반환 (매주 1건씩 7일 간격 자동 업데이트)
export function getNationwideReviews(): NationwideReviewItem[] {
  return RAW_NATIONWIDE_REVIEWS.map((item) => ({
    ...item,
    date: getFormattedDateForWeeksAgo(item.weeksAgo),
  }));
}
